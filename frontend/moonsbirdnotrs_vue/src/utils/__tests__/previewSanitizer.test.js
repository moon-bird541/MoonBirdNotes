import assert from 'node:assert/strict'
import { describe, it } from 'vitest'

import { renderMarkdownPreview } from '../markdownPreview.js'
import { sanitizePreviewHtml } from '../previewSanitizer.js'
import { renderAgentAnswer } from '../renderAgentAnswer.js'

const renderSafe = (markdown) => sanitizePreviewHtml(renderMarkdownPreview(markdown))

describe('sanitizePreviewHtml', () => {
  it('returns an empty string for empty input', () => {
    assert.equal(sanitizePreviewHtml(''), '')
  })

  it('removes script tags and inline event handlers', () => {
    const html = sanitizePreviewHtml('<p onclick="alert(1)">x</p><script>alert(1)</script>')

    assert.ok(!html.includes('<script'))
    assert.ok(!html.includes('onclick'))
    assert.ok(html.includes('x'))
  })

  it('drops style attributes and style tags', () => {
    const html = sanitizePreviewHtml('<style>body{display:none}</style><p style="color:red">x</p>')

    assert.ok(!html.includes('<style'))
    assert.ok(!html.includes('style="color:red"'))
  })

  it('drops iframe, object, embed and form', () => {
    const html = sanitizePreviewHtml(
      '<iframe src="https://evil"></iframe><object></object><embed><form></form>',
    )

    assert.equal(html.trim(), '')
  })

  it('keeps the data attributes the code-block extensions rely on', () => {
    const html = sanitizePreviewHtml('<div class="moonbird-code" data-mb-lang="js" data-mb-title="a.js"></div>')

    assert.ok(html.includes('data-mb-lang="js"'))
    assert.ok(html.includes('data-mb-title="a.js"'))
  })
})

describe('renderMarkdownPreview + sanitizePreviewHtml', () => {
  it('renders a fenced code block through the shared extension renderer', () => {
    const html = renderSafe(['```js title="app.js" showLineNumbers', 'const a = 1', '```'].join('\n'))

    assert.ok(html.includes('moonbird-code'))
    assert.ok(html.includes('data-mb-title="app.js"'))
    assert.ok(html.includes('moonbird-code-lineno'))
  })

  it('neutralises a javascript: link', () => {
    const html = renderSafe('[click](javascript:alert(1))')

    assert.ok(!/href="javascript:/i.test(html))
  })

  it('neutralises an image with an onerror payload', () => {
    const html = renderSafe('<img src=x onerror="alert(1)">')

    assert.ok(!html.includes('onerror'))
  })

  it('keeps the code-group tabs generated by directives', () => {
    const html = renderSafe(
      ['::: code-group labels=[a.js, b.py]', '```js', 'a()', '```', '```py', 'b()', '```', ':::'].join('\n'),
    )

    assert.ok(html.includes('moonbird-code-tabs'))
    assert.ok(html.includes('role="tablist"'))
  })

  it('renders a callout container as a blockquote', () => {
    const html = renderSafe([':::warning[注意]', '别删库', ':::'].join('\n'))

    assert.ok(html.toLowerCase().includes('<blockquote'))
    assert.ok(html.includes('[!WARNING]'))
  })
})

describe('renderAgentAnswer', () => {
  it('returns an empty string for non-string input', () => {
    assert.equal(renderAgentAnswer(null), '')
    assert.equal(renderAgentAnswer('   '), '')
  })

  it('strips scripts from the model answer', () => {
    const html = renderAgentAnswer('hello <script>alert(1)</script>')

    assert.ok(!html.includes('<script'))
    assert.ok(html.includes('hello'))
  })

  it('wraps fenced code blocks in the agent code block chrome', () => {
    const html = renderAgentAnswer(['```js', 'const a = 1', '```'].join('\n'))

    assert.ok(html.includes('agent-code-block'))
    assert.ok(html.includes('agent-code-copy'))
    assert.ok(html.includes('复制代码'))
  })

  it('does not treat a language tag as HTML', () => {
    const html = renderAgentAnswer(['```<img src=x>', 'a', '```'].join('\n'))

    assert.ok(!html.includes('<img src=x>'))
  })
})
