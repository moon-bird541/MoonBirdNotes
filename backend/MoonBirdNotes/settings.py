def build_cache_config(debug, cache_url):
    if cache_url:
        return {
            'default': {
                'BACKEND': 'django.core.cache.backends.redis.RedisCache',
                'LOCATION': cache_url,
            }
        }

    if debug:
        return {
            'default': {
                'BACKEND': 'django.core.cache.backends.locmem.LocMemCache',
                'LOCATION': 'moonbirdnotes-dev-cache',
            }
        }

    raise ImproperlyConfigured('CACHE_URL is required when DEBUG=False so login throttling uses a shared cache.')

